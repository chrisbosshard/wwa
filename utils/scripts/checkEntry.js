export function checkEmail(email) {
  const emailRegex =
    /^(([^<>()[\]\\.,;:\s@\"]+(\.[^<>()[\]\\.,;:\s@\"]+)*)|(\".+\"))@((\[[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}\])|(([a-zA-Z\-0-9]+\.)+[a-zA-Z]{2,}))$/;
  if (emailRegex.test(email) && email !== "") {
    return true;
  }
  return false;
}

export function checkZipcode(zipcode) {
  if (isNaN(zipcode) || zipcode.length !== 4) {
    return false;
  }
  return true;
}

